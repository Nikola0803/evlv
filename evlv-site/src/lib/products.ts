export function getProducts() {
  return applyInventorySnapshot(products).map(applyStorefrontPrice).map(withQuantityPricing);
}

/** Normalize every catalog source to the same public quantity offer. Live
 * inventory can change a vial price without leaving an old case total behind. */
export function withQuantityPricing(product: Product): Product {
  const savePercent = 10;
  const qty = 10;
  return {
    ...product,
    bulkOption: {
      qty,
      savePercent,
      price: Number((getQuantityUnitPrice(product.price, qty) * qty).toFixed(2)),
    },
  };
}

export function getFeaturedProducts() {
  // EVLV-3/EVLV-2/EVLV-1 (the metabolic-research trio) lead as top products per
  // request -- order here is deliberate, not just a filter, since
  // FeaturedProducts renders these in array order.
  const inventoryProducts = getProducts();
  const order = ["evlv-3-10mg", "evlv-2-10mg", "evlv-1-5mg", "aod-9604-10mg"];
  return order
    .map((slug) => inventoryProducts.find((p) => p.slug === slug))
    .filter((p): p is Product => Boolean(p?.inStock));
}

export function getProductBySlug(slug: string) {
  return getProducts().find((p) => p.slug === slug);
}

/**
 * Every published, in-stock SKU gets its own shop card. Dose variants keep
 * their own pages and cards instead of being collapsed into one representative
 * compound. When a resolved catalog is provided, preserve its live Google/CRM
 * stock state; only the static default needs the bundled inventory snapshot.
 */
export function getShopListProducts(source?: Product[]) {
  const catalog = source ?? getProducts();
  return catalog.filter((product) => product.inStock);
}

export function getRelatedProducts(slug: string, limit = 4) {
  const current = getProductBySlug(slug);
  if (!current) return [];
  return getProducts()
    .filter((p) => p.slug !== slug && p.category === current.category && p.inStock)
    .slice(0, limit);
}

